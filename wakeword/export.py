"""Export trained models for ESPHome: manifest (model JSON v2) and a YAML snippet per device.

ESPHome loads a microWakeWord model from a JSON manifest that points to the ``.tflite`` file. The
files go to the ESPHome config folder (``/config/esphome/wake_words/`` in Home Assistant) or to any
web server; each device in household.yaml gets a snippet that adds its words to the firmware.
Home Assistant Voice PE then offers them in the two "Wake word" selects (one per assistant slot).
"""

from __future__ import annotations

import json
from pathlib import Path
import shutil

from .household import STOCK_WORDS, Household
from .synthetic import build_dir

EXPORT_DIR = "export"
# Where microwakeword.model_train_eval writes the quantized streaming model.
TRAINED_MODEL = "trained/tflite_stream_state_internal_quant/stream_state_internal_quant.tflite"
DEFAULT_CUTOFF = 0.97
DEFAULT_WINDOW = 5
TENSOR_ARENA_SIZE = 30000
MINIMUM_ESPHOME_VERSION = "2024.7.0"
WAKE_WORDS_FOLDER = "wake_words"


def manifest(household: Household, word: str, cutoff: float = DEFAULT_CUTOFF, window: int = DEFAULT_WINDOW,
             author: str = "", website: str = "") -> dict:
    """The model manifest in ESPHome's v2 format."""
    if not 0 < cutoff < 1:
        raise ValueError("cutoff must be between 0 and 1")
    if window < 1:
        raise ValueError("window must be at least 1")
    entry = household.words[word]
    data = {
        "type": "micro",
        "wake_word": entry.wake_word,
        "author": author or household.name,
        "website": website,
        "model": f"{word}.tflite",
        "trained_languages": list(entry.trained_languages),
        "version": 2,
        "micro": {
            "probability_cutoff": cutoff,
            "sliding_window_size": window,
            "feature_step_size": 10,
            "tensor_arena_size": TENSOR_ARENA_SIZE,
            "minimum_esphome_version": MINIMUM_ESPHOME_VERSION,
        },
    }
    if not website:
        del data["website"]
    return data


def export_dir(household: Household) -> Path:
    return household.data_dir / EXPORT_DIR


def export_word(household: Household, word: str, model: Path | None = None, **kwargs) -> list[Path]:
    """Copy the trained model and write its manifest to `data/export/wake_words/`."""
    model = Path(model) if model else build_dir(household, word) / TRAINED_MODEL
    if not model.exists():
        raise FileNotFoundError(f"{model}: train the model first (or pass --model)")
    folder = export_dir(household) / WAKE_WORDS_FOLDER
    folder.mkdir(parents=True, exist_ok=True)
    tflite = folder / f"{word}.tflite"
    shutil.copyfile(model, tflite)
    json_path = folder / f"{word}.json"
    json_path.write_text(json.dumps(manifest(household, word, **kwargs), indent=2, ensure_ascii=False) + "\n",
                         encoding="utf-8")
    return [tflite, json_path]


def model_ref(word: str, url_base: str | None) -> str:
    if url_base:
        return f"{url_base.rstrip('/')}/{word}.json"
    return f"{WAKE_WORDS_FOLDER}/{word}.json"


def device_yaml(household: Household, device: str, url_base: str | None = None) -> str:
    """ESPHome snippet adding the device's own words (stock words are already in the firmware)."""
    words = household.devices[device]
    own = [w for w in words if w not in STOCK_WORDS]
    lines = [
        f"# {device}: wake words {', '.join(words)} — generated by `wakeword export`.",
        "# Paste below the existing `packages:` block of the device (keep the package as it is).",
    ]
    if own:
        lines += ["micro_wake_word:", "  models:"]
        for word in own:
            lines += [f"    - model: {model_ref(word, url_base)}", f"      id: {word}"]
    else:
        lines.append("# Only stock words — nothing to add, just pick them in Home Assistant.")
    lines += ["", "# After flashing, in Home Assistant set:"]
    labels = {w: household.words[w].wake_word if w in household.words else w.replace("_", " ").title() for w in words}
    for slot, word in enumerate(words, start=1):
        lines.append(f"#   assistant slot {slot} wake word: {labels[word]}")
    return "\n".join(lines) + "\n"


def write_device_snippets(household: Household, url_base: str | None = None) -> list[Path]:
    folder = export_dir(household) / "devices"
    folder.mkdir(parents=True, exist_ok=True)
    paths = []
    for device in household.devices:
        path = folder / f"{device}.yaml"
        path.write_text(device_yaml(household, device, url_base), encoding="utf-8")
        paths.append(path)
    return paths
