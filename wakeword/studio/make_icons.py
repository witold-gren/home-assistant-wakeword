"""Write ``www/vendor/mdi.js``: the paths of the Material Design Icons the studio uses, so it needs no CDN.

    python -m wakeword.studio.make_icons <path of @mdi/js mdi.js>     (make icons)

Every ``mdi:<name>`` written in the studio's files is looked up in ``mdi.js`` of ``@mdi/js`` (Apache 2.0).
"""

from __future__ import annotations

import json
from pathlib import Path
import re
import sys

WWW = Path(__file__).parent / "www"
OUT = WWW / "vendor" / "mdi.js"
NAME = re.compile(r"mdi:[a-z0-9-]+")
EXPORT = re.compile(r'^export var (mdi\w+) = "([^"]+)";', re.M)
FALLBACK = "mdi:help-circle-outline"


def used_icons(folder: Path = WWW) -> set[str]:
    names = {FALLBACK}
    for file in folder.rglob("*"):
        if file.suffix in (".js", ".html") and "vendor" not in file.parts:
            names.update(NAME.findall(file.read_text(encoding="utf-8")))
    return names


def js_name(icon: str) -> str:
    """mdi:chevron-down -> mdiChevronDown"""
    return "mdi" + "".join(part.capitalize() for part in icon.removeprefix("mdi:").split("-"))


def write(source: Path, out: Path = OUT) -> list[str]:
    paths = dict(EXPORT.findall(source.read_text(encoding="utf-8")))
    icons = sorted(used_icons())
    missing = [icon for icon in icons if js_name(icon) not in paths]
    if missing:
        raise SystemExit(f"not in {source}: {', '.join(missing)}")
    table = {icon: paths[js_name(icon)] for icon in icons}
    out.write_text("// Generated by `python -m wakeword.studio.make_icons` from @mdi/js (Apache 2.0) - do not edit.\n"
                   f"export const ICONS = {json.dumps(table, indent=1)};\n", encoding="utf-8")
    return icons


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    print(f"{len(write(Path(sys.argv[1])))} icons in {OUT}")
