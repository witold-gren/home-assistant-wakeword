/** A text of the editor (else of the training panel's pack, else the key), with {name} filled in. */
export function translate(language, key, values = {}, panel = {}) {
  const text = STRINGS[language]?.[key] ?? STRINGS.en[key] ?? panel[key] ?? key;
  return String(text).replace(/\{(\w+)\}/g, (_, name) => (values[name] ?? `{${name}}`));
}

export function hasStudioText(key) {
  return key in STRINGS.en;
}

